<?php
/**
 * Generates docs/HOOKS.md from the docblocks above do_action()/apply_filters() calls.
 *
 * Usage: php bin/hook-docs.php            (writes docs/HOOKS.md)
 *        php bin/hook-docs.php --check    (exit 1 when a hook has no docblock)
 *
 * @package Memberkin
 */

// phpcs:disable -- developer tool, not loaded by WordPress.

$root  = dirname( __DIR__ );
$hooks = array();
$files = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $root . '/src' ) );
$list  = array();
foreach ( $files as $file ) {
	if ( 'php' === $file->getExtension() ) {
		$list[] = $file->getPathname();
	}
}
foreach ( glob( $root . '/templates/*/*.php' ) as $file ) {
	$list[] = $file;
}
sort( $list );

foreach ( $list as $path ) {
	$tokens   = token_get_all( file_get_contents( $path ) );
	$last_doc = null;
	$doc_line = 0;
	$count    = count( $tokens );
	for ( $i = 0; $i < $count; $i++ ) {
		$t = $tokens[ $i ];
		if ( is_array( $t ) && T_DOC_COMMENT === $t[0] ) {
			$last_doc = $t[1];
			$doc_line = $t[2] + substr_count( $t[1], "\n" );
			continue;
		}
		if ( ! is_array( $t ) || T_STRING !== $t[0] || ! in_array( $t[1], array( 'do_action', 'apply_filters', 'do_action_ref_array', 'apply_filters_ref_array' ), true ) ) {
			continue;
		}
		// Skip method definitions / calls on objects.
		$prev = $tokens[ $i - 1 ] ?? null;
		if ( is_array( $prev ) && in_array( $prev[0], array( T_OBJECT_OPERATOR, T_DOUBLE_COLON, T_FUNCTION ), true ) ) {
			continue;
		}
		// First argument expression.
		$j     = $i + 1;
		$depth = 0;
		$name  = '';
		while ( $j < $count ) {
			$tok = $tokens[ $j ];
			$txt = is_array( $tok ) ? $tok[1] : $tok;
			if ( '(' === $txt ) {
				++$depth;
				if ( 1 === $depth ) {
					++$j;
					continue;
				}
			} elseif ( ')' === $txt ) {
				--$depth;
				if ( 0 === $depth ) {
					break;
				}
			} elseif ( ',' === $txt && 1 === $depth ) {
				break;
			}
			if ( $depth >= 1 ) {
				$name .= $txt;
			}
			++$j;
		}
		$name = trim( preg_replace( '/\s+/', ' ', $name ) );
		if ( ! preg_match( "/^'memberkin_/", $name ) ) {
			continue;
		}
		$display = preg_replace( "/'\s*\.\s*\\$([a-z_]+)(?:\s*\.\s*'([^']*)')?/", '{$$1}$2', $name );
		$display = trim( str_replace( "'", '', $display ) );
		$line    = $t[2];
		$doc     = ( $last_doc && $line - $doc_line <= 2 ) ? $last_doc : null;
		$type    = str_starts_with( $t[1], 'do_action' ) ? 'action' : 'filter';
		$key     = $type . ':' . $display;
		$entry   = array(
			'type'   => $type,
			'name'   => $display,
			'where'  => array( substr( $path, strlen( $root ) + 1 ) . ':' . $line ),
			'doc'    => $doc,
		);
		if ( isset( $hooks[ $key ] ) ) {
			$hooks[ $key ]['where'][] = $entry['where'][0];
			$hooks[ $key ]['doc']   ??= $doc;
		} else {
			$hooks[ $key ] = $entry;
		}
		$last_doc = null;
	}
}
ksort( $hooks );

/**
 * Docblock → [summary, params].
 *
 * @param string|null $doc Docblock.
 */
function memberkin_parse_doc( ?string $doc ): array {
	if ( null === $doc ) {
		return array( '', array() );
	}
	$lines   = array_map( static fn( $l ) => preg_replace( '#^\s*(/\*\*|\*/|\*)\s?#', '', $l ), explode( "\n", $doc ) );
	$summary = array();
	$params  = array();
	foreach ( $lines as $l ) {
		if ( preg_match( '/^@param\s+(\S+)\s+(\$\S+)\s*(.*)$/', trim( $l ), $m ) ) {
			$params[] = array( $m[1], $m[2], $m[3] );
		} elseif ( ! str_starts_with( trim( $l ), '@' ) && ! $params ) {
			$summary[] = trim( $l );
		}
	}
	return array( trim( implode( ' ', array_filter( $summary, 'strlen' ) ) ), $params );
}

$missing = array_filter( $hooks, static fn( $h ) => null === $h['doc'] );
if ( in_array( '--check', $argv, true ) ) {
	foreach ( $missing as $h ) {
		fwrite( STDERR, "Undocumented {$h['type']} {$h['name']} at {$h['where'][0]}\n" );
	}
	exit( $missing ? 1 : 0 );
}

$out  = "# Memberkin — hooks reference\n\n";
$out .= "Generated by `php bin/hook-docs.php` from the docblocks in the source. Do not edit by hand.\n\n";
$out .= sprintf( "%d actions and %d filters. Names in `{braces}` are dynamic parts.\n\n", count( array_filter( $hooks, static fn( $h ) => 'action' === $h['type'] ) ), count( array_filter( $hooks, static fn( $h ) => 'filter' === $h['type'] ) ) );
foreach ( array( 'action' => 'Actions', 'filter' => 'Filters' ) as $type => $title ) {
	$out .= "## {$title}\n\n";
	foreach ( $hooks as $h ) {
		if ( $h['type'] !== $type ) {
			continue;
		}
		[ $summary, $params ] = memberkin_parse_doc( $h['doc'] );
		$out                 .= "### `{$h['name']}`\n\n" . ( '' !== $summary ? $summary . "\n\n" : "_No description._\n\n" );
		if ( $params ) {
			$out .= "| Parameter | Type | Description |\n|---|---|---|\n";
			foreach ( $params as [ $ptype, $pname, $pdesc ] ) {
				$out .= '| `' . $pname . '` | `' . str_replace( '|', '\\|', $ptype ) . '` | ' . str_replace( '|', '\\|', $pdesc ) . " |\n";
			}
			$out .= "\n";
		}
		$out .= 'Source: ' . implode( ', ', array_map( static fn( $w ) => '`' . $w . '`', $h['where'] ) ) . "\n\n";
	}
}
file_put_contents( $root . '/docs/HOOKS.md', $out );
printf( "%d hooks written to docs/HOOKS.md (%d without docblock).\n", count( $hooks ), count( $missing ) );
